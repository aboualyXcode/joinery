"""Render a dataset as DDL and INSERT statements for each supported dialect.

The same definitions build the SQLite images that power the playground and
the downloadable scripts learners can load into their own databases.
"""

from __future__ import annotations

from collections.abc import Iterator

from .model import Column, Dataset, Table

DIALECTS = ("sqlite", "postgres", "mysql", "mssql", "duckdb")
DIALECT_NAMES = {
    "sqlite": "SQLite",
    "postgres": "PostgreSQL",
    "mysql": "MySQL",
    "mssql": "SQL Server",
    "duckdb": "DuckDB",
}
LOAD_HINTS = {
    "sqlite": "sqlite3 {id}.db < {id}.sqlite.sql",
    "postgres": "psql -d mydb -f {id}.postgres.sql",
    "mysql": "mysql mydb < {id}.mysql.sql",
    "mssql": "sqlcmd -d mydb -i {id}.mssql.sql",
    "duckdb": "duckdb {id}.duckdb < {id}.duckdb.sql",
}

_TYPES: dict[str, dict[str, str]] = {
    "integer": {"sqlite": "INTEGER", "postgres": "integer", "mysql": "INT", "mssql": "INT", "duckdb": "INTEGER"},
    "bigint": {"sqlite": "INTEGER", "postgres": "bigint", "mysql": "BIGINT", "mssql": "BIGINT", "duckdb": "BIGINT"},
    "text": {"sqlite": "TEXT", "postgres": "text", "mysql": "TEXT", "mssql": "NVARCHAR(MAX)", "duckdb": "VARCHAR"},
    "boolean": {"sqlite": "BOOLEAN", "postgres": "boolean", "mysql": "BOOLEAN", "mssql": "BIT", "duckdb": "BOOLEAN"},
    "date": {"sqlite": "DATE", "postgres": "date", "mysql": "DATE", "mssql": "DATE", "duckdb": "DATE"},
    "timestamp": {"sqlite": "TIMESTAMP", "postgres": "timestamp", "mysql": "DATETIME", "mssql": "DATETIME2(0)",
                  "duckdb": "TIMESTAMP"},
    "json": {"sqlite": "TEXT", "postgres": "jsonb", "mysql": "JSON", "mssql": "NVARCHAR(MAX)", "duckdb": "VARCHAR"},
}


def _check_dialect(dialect: str) -> None:
    if dialect not in DIALECTS:
        raise ValueError(f"unsupported dialect: {dialect}")


def column_type(col: Column, dialect: str) -> str:
    _check_dialect(dialect)
    base, args = col.base_type, col.type_args
    if base == "decimal":
        precision, scale = (args + (2,))[:2] if args else (12, 2)
        return f"numeric({precision},{scale})" if dialect == "postgres" else f"DECIMAL({precision},{scale})"
    if base == "varchar":
        length = args[0] if args else 255
        return {"sqlite": f"VARCHAR({length})", "postgres": f"varchar({length})", "mysql": f"VARCHAR({length})",
                "mssql": f"NVARCHAR({length})", "duckdb": "VARCHAR"}[dialect]
    return _TYPES[base][dialect]


def quote_string(text: str, dialect: str) -> str:
    escaped = text.replace("'", "''")
    if dialect == "mysql":
        escaped = escaped.replace("\\", "\\\\")
    return f"N'{escaped}'" if dialect == "mssql" else f"'{escaped}'"


def literal(value: object, col: Column, dialect: str) -> str:
    if value is None:
        return "NULL"
    base = col.base_type
    if base == "boolean":
        if dialect in ("sqlite", "mssql"):
            return "1" if value else "0"
        return "TRUE" if value else "FALSE"
    if base in ("integer", "bigint"):
        return str(int(value))  # type: ignore[call-overload]
    if base == "decimal":
        scale = col.type_args[1] if len(col.type_args) > 1 else 2
        return f"{float(value):.{scale}f}"  # type: ignore[arg-type]
    return quote_string(str(value), dialect)


def _default(col: Column, dialect: str) -> str:
    assert col.default is not None
    if col.base_type == "boolean" and dialect in ("sqlite", "mssql"):
        return "1" if col.default.upper() == "TRUE" else "0"
    if dialect == "mssql" and col.default.startswith("'"):
        return "N" + col.default
    return col.default


def _identity(table: Table, col: Column) -> bool:
    return col.identity and table.primary_key == [col.name]


def column_definition(table: Table, col: Column, dialect: str) -> str:
    sql_type = column_type(col, dialect)
    if _identity(table, col):
        return {
            "sqlite": f"{col.name} INTEGER PRIMARY KEY",
            "postgres": f"{col.name} {sql_type} GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            "mysql": f"{col.name} {sql_type} NOT NULL AUTO_INCREMENT PRIMARY KEY",
            "mssql": f"{col.name} {sql_type} IDENTITY(1,1) NOT NULL PRIMARY KEY",
            "duckdb": f"{col.name} {sql_type} PRIMARY KEY DEFAULT nextval('{table.name}_{col.name}_seq')",
        }[dialect]
    parts = [col.name, sql_type]
    if not col.nullable or col.primary_key:
        parts.append("NOT NULL")
    if col.default is not None:
        parts.append(f"DEFAULT {_default(col, dialect)}")
    return " ".join(parts)


def create_table(table: Table, dialect: str) -> str:
    lines = [column_definition(table, col, dialect) for col in table.columns]
    pk = table.primary_key
    if pk and not any(_identity(table, c) for c in table.columns):
        lines.append(f"CONSTRAINT pk_{table.name} PRIMARY KEY ({', '.join(pk)})")
    for col in table.columns:
        if col.unique:
            lines.append(f"CONSTRAINT uq_{table.name}_{col.name} UNIQUE ({col.name})")
    for col in table.columns:
        if col.check:
            lines.append(f"CONSTRAINT ck_{table.name}_{col.name} CHECK ({col.check})")
        if col.base_type == "boolean" and dialect == "sqlite":
            lines.append(f"CONSTRAINT ck_{table.name}_{col.name}_bool CHECK ({col.name} IN (0, 1))")
    for col in table.columns:
        if col.references:
            lines.append(
                f"CONSTRAINT fk_{table.name}_{col.name} FOREIGN KEY ({col.name}) "
                f"REFERENCES {col.ref_table} ({col.ref_column})"
            )
    body = ",\n  ".join(lines)
    return f"CREATE TABLE {table.name} (\n  {body}\n);"


def insert_statements(table: Table, dialect: str, batch_size: int = 250) -> Iterator[str]:
    columns = ", ".join(table.column_names)
    for start in range(0, len(table.rows), batch_size):
        chunk = table.rows[start:start + batch_size]
        values = ",\n  ".join(
            "(" + ", ".join(literal(v, c, dialect) for v, c in zip(row, table.columns, strict=True)) + ")"
            for row in chunk
        )
        yield f"INSERT INTO {table.name} ({columns}) VALUES\n  {values};"


def _identity_column(table: Table) -> Column | None:
    return next((c for c in table.columns if _identity(table, c)), None)


def create_script(dataset: Dataset, dialect: str, *, include_data: bool = True) -> str:
    """A complete, re-runnable script that recreates the dataset."""
    _check_dialect(dialect)
    tables = dataset.ordered_tables()
    out = [
        f"-- Joinery sample dataset: {dataset.title} ({dataset.id})",
        f"-- Dialect: {DIALECT_NAMES[dialect]}",
        f"-- {dataset.summary}",
        f"-- Load it with: {LOAD_HINTS[dialect].format(id=dataset.id)}",
        "",
    ]
    for table in reversed(tables):
        out.append(f"DROP TABLE IF EXISTS {table.name};")
    if dialect == "duckdb":
        for table in tables:
            col = _identity_column(table)
            if col:
                out.append(f"DROP SEQUENCE IF EXISTS {table.name}_{col.name}_seq;")
    out.append("")
    for table in tables:
        col = _identity_column(table)
        if dialect == "duckdb" and col:
            index = table.column_names.index(col.name)
            start = max((row[index] for row in table.rows), default=0) + 1
            out.append(f"CREATE SEQUENCE {table.name}_{col.name}_seq START {start};")
        out.append(create_table(table, dialect))
        out.append("")
    if include_data:
        for table in tables:
            if not table.rows:
                continue
            identity = _identity_column(table)
            if dialect == "mssql" and identity:
                out.append(f"SET IDENTITY_INSERT {table.name} ON;")
            out.extend(insert_statements(table, dialect))
            if dialect == "mssql" and identity:
                out.append(f"SET IDENTITY_INSERT {table.name} OFF;")
            if dialect == "postgres" and identity:
                out.append(
                    f"SELECT setval(pg_get_serial_sequence('{table.name}', '{identity.name}'), "
                    f"(SELECT max({identity.name}) FROM {table.name}));"
                )
            out.append("")
    for table in tables:
        for index in table.indexes:
            unique = "UNIQUE " if index.unique else ""
            out.append(f"CREATE {unique}INDEX {index.name} ON {table.name} ({', '.join(index.columns)});")
    return "\n".join(out).rstrip() + "\n"
